#!/usr/bin/env node
/**
 * inline-sprites.js — Bundle the default avatar into the package.
 *
 * Avatars live in <repo>/avatars/<name>/ (avatar.json + shime1..46.png). Only the one
 * marked `"bundled": true` in its avatar.json is inlined (as base64 data URLs) into
 * src/characters/characters.js — that is the offline default. Every other avatar is
 * downloaded by name from the CDN when a site asks for it (see src/characters/remote.js).
 *
 * Usage: node scripts/inline-sprites.js
 */
import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname  = dirname(fileURLToPath(import.meta.url));
const avatarsDir = join(__dirname, '..', '..', '..', 'avatars');
const outDir     = join(__dirname, '..', 'src', 'characters');
const outFile    = join(outDir, 'characters.js');

function readAvatar(folder) {
  const dir = join(avatarsDir, folder);
  let meta;
  try {
    meta = JSON.parse(readFileSync(join(dir, 'avatar.json'), 'utf8'));
  } catch (e) {
    throw new Error(`${folder}/avatar.json is missing or invalid: ${e.message}`);
  }
  return { dir, meta };
}

function main() {
  if (!existsSync(avatarsDir)) {
    console.error(`✗ No avatars directory at ${avatarsDir}`);
    process.exit(1);
  }

  const folders = readdirSync(avatarsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  const bundled = [];
  for (const folder of folders) {
    const { dir, meta } = readAvatar(folder);
    if (meta.bundled === true) bundled.push({ folder, dir, meta });
  }
  if (bundled.length !== 1) {
    console.error(`✗ Exactly one avatar must have "bundled": true in its avatar.json (found ${bundled.length}).`);
    process.exit(1);
  }

  const characters = {};
  let sprites = 0;
  for (const { folder, dir, meta } of bundled) {
    const files = readdirSync(dir)
      .filter((f) => /^shime\d+\.png$/.test(f))
      .sort((a, b) => parseInt(a.match(/\d+/)[0], 10) - parseInt(b.match(/\d+/)[0], 10));
    const spriteData = {};
    for (const f of files) spriteData[f] = `data:image/png;base64,${readFileSync(join(dir, f)).toString('base64')}`;
    characters[folder] = {
      name: meta.name || folder,
      displayName: meta.displayName || folder,
      author: meta.author || '',
      spriteData,
    };
    sprites += files.length;
    console.log(`  ✓ ${folder.padEnd(16)} ${(meta.displayName || folder).padEnd(16)} ${files.length} sprites (bundled)`);
  }

  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  const code = [
    '// Auto-generated by scripts/inline-sprites.js — do not edit.',
    '// Regenerate with: npm run inline-sprites',
    '// Only the avatar marked "bundled": true in avatars/<name>/avatar.json is inlined; others load from the CDN.',
    '',
    'export const CHARACTERS = ' + JSON.stringify(characters, null, 2) + ';',
    '',
    'export const DEFAULT_CHARACTER = ' + JSON.stringify(bundled[0].folder) + ';',
    '',
  ].join('\n');
  writeFileSync(outFile, code, 'utf8');
  console.log(`✓ Wrote ${outFile} (${Math.round(Buffer.byteLength(code) / 1024)} KB, ${sprites} sprites)`);
}

main();
